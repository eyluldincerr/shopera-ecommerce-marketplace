    CONSTRAINT CK_ORDER_Amounts CHECK
    (
        SubtotalAmount>=0 AND DiscountAmount>=0 AND ShippingAmount>=0 AND TotalAmount>=0
        AND TotalAmount=SubtotalAmount-DiscountAmount+ShippingAmount
    ),
    CONSTRAINT CK_ORDER_Currency CHECK (CurrencyCode=UPPER(CurrencyCode)),
    CONSTRAINT FK_ORDER_Buyer FOREIGN KEY (BuyerUserID,BuyerRole) REFERENCES dbo.USER_ACCOUNT(UserID,Role),
    CONSTRAINT FK_ORDER_Store FOREIGN KEY (StoreID) REFERENCES dbo.STORE(StoreID),
