CREATE TABLE dbo.CUSTOMER_ORDER
(
    OrderID INT IDENTITY(1,1) NOT NULL,
    OrderNumber NVARCHAR(30) NOT NULL,
    BuyerUserID INT NOT NULL,
    BuyerRole AS CONVERT(NVARCHAR(20),N'BUYER') PERSISTED,
    StoreID INT NOT NULL,
    CouponID INT NULL,
    OrderDate DATETIME2(0) NOT NULL CONSTRAINT DF_ORDER_Date DEFAULT SYSUTCDATETIME(),
    OrderStatus NVARCHAR(20) NOT NULL CONSTRAINT DF_ORDER_Status DEFAULT N'PENDING',
    SubtotalAmount DECIMAL(12,2) NOT NULL,
    DiscountAmount DECIMAL(12,2) NOT NULL CONSTRAINT DF_ORDER_Discount DEFAULT 0,
    ShippingAmount DECIMAL(12,2) NOT NULL CONSTRAINT DF_ORDER_Shipping DEFAULT 0,
    TotalAmount DECIMAL(12,2) NOT NULL,
    CurrencyCode CHAR(3) NOT NULL CONSTRAINT DF_ORDER_Currency DEFAULT 'EUR',
