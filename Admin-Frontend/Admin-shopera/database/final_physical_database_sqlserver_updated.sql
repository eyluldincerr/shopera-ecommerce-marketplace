/* ============================== IDENTITY ============================== */
CREATE TABLE dbo.USER_ACCOUNT
(
    UserID INT IDENTITY(1,1) NOT NULL,
    FullName NVARCHAR(150) NOT NULL,
    Email NVARCHAR(255) NOT NULL,
    PasswordHash NVARCHAR(255) NOT NULL,
    PhoneNumber NVARCHAR(30) NULL,
    RegistrationDate DATETIME2(0) NOT NULL CONSTRAINT DF_USER_RegistrationDate DEFAULT SYSUTCDATETIME(),
    Role NVARCHAR(20) NOT NULL,
    AccountStatus NVARCHAR(20) NOT NULL CONSTRAINT DF_USER_Status DEFAULT N'ACTIVE',
    PermissionLevel NVARCHAR(50) NULL,
    CONSTRAINT PK_USER_ACCOUNT PRIMARY KEY CLUSTERED (UserID),
    CONSTRAINT UQ_USER_Email UNIQUE (Email),
    CONSTRAINT UQ_USER_UserID_Role UNIQUE (UserID, Role),
    CONSTRAINT CK_USER_Email CHECK (Email LIKE N'%_@_%._%'),
    CONSTRAINT CK_USER_Role CHECK (Role IN (N'BUYER',N'SELLER',N'ADMIN')),
    CONSTRAINT CK_USER_Status CHECK (AccountStatus IN (N'ACTIVE',N'INACTIVE',N'SUSPENDED')),
    CONSTRAINT CK_USER_AdminPermission CHECK
    (
        (Role=N'ADMIN' AND PermissionLevel IN (N'SUPER_ADMIN',N'MANAGER',N'SUPPORT'))
        OR (Role<>N'ADMIN' AND PermissionLevel IS NULL)
    )
);
GO

